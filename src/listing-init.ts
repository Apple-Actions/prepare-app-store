import {createInterface} from 'node:readline'
import {existsSync, mkdirSync, writeFileSync} from 'node:fs'
import {dirname} from 'node:path'
import {discoverListingFromRepo, mergeListingSources} from './listing-discover'
import {ListingFile, loadListingFile} from './listing-file'
import {ListingPullResult} from './listing-pull'

export type InitResult = {
  listing: ListingFile
  missing: string[]
  written: boolean
  reviewFlagsHint?: string
}

export function missingListingFields(
  listing: ListingFile,
  platform: string
): string[] {
  const missing: string[] = []
  if (!listing.description?.trim()) missing.push('description')
  if (!listing.supportUrl?.trim()) missing.push('supportUrl')
  if (!listing.privacyPolicyUrl?.trim()) missing.push('privacyPolicyUrl')
  if (!listing.ageRating) missing.push('ageRating')
  const platformKey = platform === 'MAC_OS' ? 'mac' : 'ios'
  const shots = listing.screenshots?.[platformKey] || []
  if (!shots.length) missing.push(`screenshots.${platformKey}`)
  return missing
}

export function serializeListingYaml(listing: ListingFile): string {
  const lines: string[] = [
    '# Generated by setup-app-store-listing.sh --init',
    '# Keep App Review phone/email out of git — pass --review-* on --apply.',
    ''
  ]

  if (listing.description !== undefined) {
    lines.push('description: |')
    for (const line of listing.description.split('\n')) {
      lines.push(`  ${line}`)
    }
  }
  writeScalar(lines, 'keywords', listing.keywords)
  writeScalar(lines, 'supportUrl', listing.supportUrl)
  writeScalar(lines, 'privacyPolicyUrl', listing.privacyPolicyUrl)
  writeScalar(lines, 'marketingUrl', listing.marketingUrl)
  writeScalar(lines, 'copyright', listing.copyright)
  writeScalar(lines, 'category', listing.category)
  writeScalar(lines, 'secondaryCategory', listing.secondaryCategory)

  if (listing.ageRating === 'none') {
    lines.push('ageRating: none')
  } else if (listing.ageRating && typeof listing.ageRating === 'object') {
    lines.push('ageRating:')
    for (const [key, value] of Object.entries(listing.ageRating)) {
      lines.push(`  ${key}: ${formatYamlScalar(value)}`)
    }
  }

  if (listing.screenshots?.mac?.length || listing.screenshots?.ios?.length) {
    lines.push('screenshots:')
    if (listing.screenshots.mac?.length) {
      lines.push('  mac:')
      for (const path of listing.screenshots.mac) {
        lines.push(`    - ${path}`)
      }
    }
    if (listing.screenshots.ios?.length) {
      lines.push('  ios:')
      for (const path of listing.screenshots.ios) {
        lines.push(`    - ${path}`)
      }
    }
  }

  lines.push('')
  return `${lines.join('\n')}\n`
}

function writeScalar(
  lines: string[],
  key: string,
  value: string | undefined
): void {
  if (value === undefined || value === '') {
    return
  }
  lines.push(`${key}: ${formatYamlScalar(value)}`)
}

function formatYamlScalar(value: string | boolean | null): string {
  if (value === null) return 'null'
  if (typeof value === 'boolean') return value ? 'true' : 'false'
  if (/[:#{}[\],&*?|>!%@`]/.test(value) || value.includes('\n')) {
    return JSON.stringify(value)
  }
  return value
}

async function promptLine(
  question: string,
  defaultValue?: string
): Promise<string> {
  const rl = createInterface({input: process.stdin, output: process.stdout})
  const suffix =
    defaultValue !== undefined && defaultValue !== ''
      ? ` [${defaultValue}]`
      : ''
  const answer: string = await new Promise(resolve => {
    rl.question(`${question}${suffix}: `, resolve)
  })
  rl.close()
  const trimmed = answer.trim()
  if (!trimmed && defaultValue !== undefined) {
    return defaultValue
  }
  return trimmed
}

async function promptForMissingListing({
  listing,
  platform,
  interactive
}: {
  listing: ListingFile
  platform: string
  interactive: boolean
}): Promise<{listing: ListingFile; skippedScreenshots: boolean}> {
  const out: ListingFile = {...listing, screenshots: {...listing.screenshots}}
  let skippedScreenshots = false

  if (!interactive) {
    return {listing: out, skippedScreenshots}
  }

  type StringField =
    | 'description'
    | 'keywords'
    | 'supportUrl'
    | 'privacyPolicyUrl'
    | 'marketingUrl'
    | 'copyright'
    | 'category'
    | 'secondaryCategory'

  const ask = async (
    key: StringField,
    label: string,
    required: boolean
  ): Promise<void> => {
    const currentStr = out[key]
    for (;;) {
      const next = await promptLine(label, currentStr)
      if (next) {
        out[key] = next
        return
      }
      if (!required) {
        return
      }
      process.stderr.write(`  ${key} is required.\n`)
    }
  }

  await ask('description', 'description', true)
  await ask('supportUrl', 'supportUrl', true)
  await ask('privacyPolicyUrl', 'privacyPolicyUrl', true)
  await ask('keywords', 'keywords (optional)', false)
  await ask('marketingUrl', 'marketingUrl (optional)', false)
  await ask('copyright', 'copyright (optional)', false)
  await ask('category', 'category ASC id (optional, e.g. UTILITIES)', false)

  const ageDefault =
    out.ageRating === 'none'
      ? 'none'
      : out.ageRating && typeof out.ageRating === 'object'
        ? 'custom'
        : 'none'
  const ageAnswer = await promptLine(
    'ageRating (none = utility preset)',
    ageDefault === 'custom' ? 'none' : ageDefault
  )
  if (!ageAnswer || ageAnswer === 'none') {
    out.ageRating = 'none'
  } else if (ageAnswer === 'custom' && typeof out.ageRating === 'object') {
    // keep pulled map
  } else {
    out.ageRating = 'none'
  }

  const platformKey = platform === 'MAC_OS' ? 'mac' : 'ios'
  const shots = out.screenshots?.[platformKey] || []
  if (!shots.length) {
    const skip = await promptLine(
      `No store/screenshots/${platformKey} images found. Type 'skip' to continue without screenshots, or Enter after adding files and re-run --init`,
      ''
    )
    if (skip.toLowerCase() === 'skip') {
      skippedScreenshots = true
    }
  }

  return {listing: out, skippedScreenshots}
}

async function promptReviewContactFlags(interactive: boolean): Promise<
  | {
      firstName: string
      lastName: string
      phone: string
      email: string
    }
  | undefined
> {
  if (!interactive) {
    return undefined
  }
  process.stdout.write(
    '\nApp Review contact (not written to listing.yml — use these flags on --apply):\n'
  )
  const firstName = await promptLine('review first name', '')
  const lastName = await promptLine('review last name', '')
  const phone = await promptLine('review phone', '')
  const email = await promptLine('review email', '')
  if (!firstName && !lastName && !phone && !email) {
    return undefined
  }
  return {firstName, lastName, phone, email}
}

export async function initListingFile({
  workspace,
  listingPath,
  platform,
  interactive,
  ascPull
}: {
  workspace: string
  listingPath: string
  platform: string
  interactive: boolean
  ascPull?: ListingPullResult
}): Promise<InitResult> {
  const repo = discoverListingFromRepo(workspace)
  let existing: ListingFile | undefined
  if (existsSync(listingPath)) {
    existing = loadListingFile(listingPath)
  }

  let listing = mergeListingSources({
    repo,
    asc: ascPull?.listing,
    existing
  })

  if (ascPull?.notes.length) {
    for (const note of ascPull.notes) {
      process.stdout.write(`note: ${note}\n`)
    }
  }

  const prompted = await promptForMissingListing({
    listing,
    platform,
    interactive
  })
  listing = prompted.listing

  // Never persist review contact into listing.yml
  delete listing.review

  const missing = missingListingFields(listing, platform)
  const yaml = serializeListingYaml(listing)
  mkdirSync(dirname(listingPath), {recursive: true})
  writeFileSync(listingPath, yaml, 'utf8')

  let reviewFlagsHint: string | undefined
  const review = await promptReviewContactFlags(interactive)
  if (review) {
    reviewFlagsHint = [
      review.firstName ? `--review-first-name '${review.firstName}'` : '',
      review.lastName ? `--review-last-name '${review.lastName}'` : '',
      review.phone ? `--review-phone '${review.phone}'` : '',
      review.email ? `--review-email '${review.email}'` : ''
    ]
      .filter(Boolean)
      .join(' ')
  }

  return {
    listing,
    missing: prompted.skippedScreenshots
      ? missing.filter(m => !m.startsWith('screenshots.'))
      : missing,
    written: true,
    reviewFlagsHint
  }
}
